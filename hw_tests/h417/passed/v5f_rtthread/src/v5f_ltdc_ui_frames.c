/*
 * Claude Code style three-frame L8 UI demo for the 800x480 RGB panel.
 *
 * Self-contained test module: embedded 8x8 font (font8x8_basic by
 * Daniel Hepper / Marcel Sondaar, public domain), 16x10 single-color
 * mascot pixel art and a fixed palette. Every frame is drawn
 * procedurally into the caller-provided full-screen L8 framebuffer;
 * no external flash access and no dynamic allocation.
 *
 * Frames, cycled every 3 seconds:
 *   0 - "Welcome back!" above the centered mascot
 *   1 - approval dialog, pointer resting on "1. Yes" (blue)
 *   2 - approval dialog, pointer resting on "2. No" (blue)
 *
 * Init order contract (v5f_hw_test.c drives this):
 *   1. clear the L8 framebuffer and start LTDC layer1 full screen
 *   2. load v5f_ltdc_ui_frames_clut_rgb888() after the layer runs
 *      (CLUT writes are reliable only once the layer is scanning)
 *   3. call v5f_ltdc_ui_frames_run(framebuffer) - never returns
 *
 * The mounted panel is rotated 180 degrees. All drawing helpers take
 * user-orientation coordinates and mirror them into framebuffer memory.
 */

