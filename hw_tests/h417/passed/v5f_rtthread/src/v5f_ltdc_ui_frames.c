static uint8_t *s_ui_fb;

static void ui_fill_rect(uint16_t x,
                         uint16_t y,
                         uint16_t width,
                         uint16_t height,
                         uint8_t color)
{
    uint32_t rotated_x;
    uint32_t rotated_y;
    uint32_t row;

    if((x >= UI_FRAME_WIDTH) || (y >= UI_FRAME_HEIGHT) ||
       (width == 0u) || (height == 0u))
    {
        return;
    }
    if((uint32_t)(x + width) > UI_FRAME_WIDTH)
    {
        width = (uint16_t)(UI_FRAME_WIDTH - x);
    }
    if((uint32_t)(y + height) > UI_FRAME_HEIGHT)
    {
        height = (uint16_t)(UI_FRAME_HEIGHT - y);
    }

    rotated_x = UI_FRAME_WIDTH - (uint32_t)x - (uint32_t)width;
    rotated_y = UI_FRAME_HEIGHT - (uint32_t)y - (uint32_t)height;
    for(row = 0u; row < height; row++)
    {
        memset(&s_ui_fb[(rotated_y + row) * UI_FRAME_WIDTH + rotated_x],
               color,
               width);
    }
}

static void ui_draw_border(uint16_t x,
                           uint16_t y,
                           uint16_t width,
                           uint16_t height,
                           uint16_t thickness,
                           uint8_t color)
{
    ui_fill_rect(x, y, width, thickness, color);
    ui_fill_rect(x, (uint16_t)(y + height - thickness), width, thickness, color);
    ui_fill_rect(x, y, thickness, height, color);
    ui_fill_rect((uint16_t)(x + width - thickness), y, thickness, height, color);
}

static void ui_draw_char(uint16_t x,
                         uint16_t y,
                         char ch,
                         uint16_t scale,
                         uint8_t color)
{
    const uint8_t *glyph;
    uint32_t row;
    uint32_t col;

    if((ch < 0x20) || (ch > 0x7E))
    {
        ch = '?';
    }
    glyph = s_ui_font8x8[ch - 0x20];
    for(row = 0u; row < UI_GLYPH_SIZE; row++)
    {
        uint8_t bits = glyph[row];

        for(col = 0u; col < UI_GLYPH_SIZE; col++)
        {
            if((bits & (uint8_t)(1u << col)) != 0u)
            {
                ui_fill_rect((uint16_t)(x + (col * scale)),
                             (uint16_t)(y + (row * scale)),
                             scale,
                             scale,
                             color);
            }
        }
    }
}

static void ui_draw_text(uint16_t x,
                         uint16_t y,
                         const char *text,
                         uint16_t scale,
                         uint8_t color)
{
    while(*text != '\0')
    {
        ui_draw_char(x, y, *text, scale, color);
        x = (uint16_t)(x + (UI_GLYPH_SIZE * scale));
        text++;
    }
}

static uint16_t ui_text_width(const char *text, uint16_t scale)
{
    return (uint16_t)(strlen(text) * UI_GLYPH_SIZE * scale);
}

static void ui_draw_text_centered(uint16_t y,
                                  const char *text,
                                  uint16_t scale,
                                  uint8_t color)
{
    uint16_t width = ui_text_width(text, scale);

    ui_draw_text((uint16_t)((UI_FRAME_WIDTH - width) / 2u), y, text, scale, color);
}

static void ui_draw_mascot(uint16_t x, uint16_t y, uint16_t cell)
{
    uint32_t row;
    uint32_t col;

    for(row = 0u; row < UI_MASCOT_ROWS; row++)
    {
        uint16_t bits = s_ui_mascot_rows[row];

        for(col = 0u; col < UI_MASCOT_COLS; col++)
        {
            if((bits & (uint16_t)(1u << col)) != 0u)
            {
                ui_fill_rect((uint16_t)(x + (col * cell)),
                             (uint16_t)(y + (row * cell)),
                             cell,
                             cell,
                             UI_COLOR_ORANGE);
            }
        }
    }
}

/* Frame 0: title and mascot placed with the reference artwork's ratios. */
static void ui_draw_welcome_frame(void)
{
    uint16_t mascot_cell = 20u;
    uint16_t mascot_width = (uint16_t)(UI_MASCOT_COLS * mascot_cell);

    ui_draw_text_centered(58u, "Welcome back!", 6u, UI_COLOR_WHITE);
    ui_draw_mascot((uint16_t)((UI_FRAME_WIDTH - mascot_width) / 2u),
                   195u,
                   mascot_cell);
}

static void ui_draw_option(uint16_t x,
                           uint16_t y,
                           const char *label,
                           uint8_t hovered)
{
    uint8_t color = hovered ? UI_COLOR_BLUE : UI_COLOR_WHITE;

    if(hovered != 0u)
    {
        ui_draw_text(x, y, ">", 3u, color);
    }
    ui_draw_text((uint16_t)(x + (2u * UI_GLYPH_SIZE * 3u)), y, label, 3u, color);
}

/* Frames 1 and 2: Claude Code permission dialog, hover on Yes or No. */
static void ui_draw_approval_frame(uint8_t hover_no)
{
    ui_draw_border(56u, 64u, 688u, 352u, 3u, UI_COLOR_BORDER);

    ui_fill_rect(92u, 102u, 12u, 12u, UI_COLOR_ORANGE);
    ui_draw_text(116u, 96u, "Bash command", 3u, UI_COLOR_WHITE);

    ui_draw_text(104u, 156u, "make -B -C firmware/h417", 3u, UI_COLOR_WHITE);
    ui_draw_text(104u, 192u, "Build H417 firmware", 3u, UI_COLOR_GRAY);

    ui_draw_text(88u, 256u, "Do you want to proceed?", 3u, UI_COLOR_WHITE);

    ui_draw_option(88u, 308u, "1. Yes", (hover_no == 0u) ? 1u : 0u);
    ui_draw_option(88u, 352u, "2. No", hover_no);
}

const uint8_t *v5f_ltdc_ui_frames_clut_rgb888(void)
{
    return s_ui_clut_rgb888;
}

void v5f_ltdc_ui_frames_run(uint8_t *framebuffer)
{
    uint32_t frame = 0u;

    s_ui_fb = framebuffer;
    for(;;)
    {
        memset(s_ui_fb, UI_COLOR_BG, UI_FRAME_WIDTH * UI_FRAME_HEIGHT);
        switch(frame)
        {
            case 1u:
                ui_draw_approval_frame(0u);
                break;
            case 2u:
                ui_draw_approval_frame(1u);
                break;
            default:
                ui_draw_welcome_frame();
                break;
        }
        ch32h417_ltdc_rgb_framebuffer_barrier();
        g_v5f_hw_test_diag.frame_count++;
        rt_thread_mdelay(UI_FRAME_HOLD_MS);
        frame = (frame + 1u) % UI_FRAME_COUNT;
    }
}
