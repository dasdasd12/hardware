static uint32_t s_last_sequence;

static void ui_draw_char(uint16_t x,
                         uint16_t y,
                         char character,
                         uint16_t scale,
                         uint8_t color)
{
    const uint8_t *glyph;
    uint32_t row;
    uint32_t column;

    if((character < 0x20) || (character > 0x7e))
    {
        character = '?';
    }
    glyph = s_ui_font8x8[(uint8_t)character - 0x20u];

    for(row = 0u; row < UI_GLYPH_SIZE; row++)
    {
        uint8_t bits = glyph[row];

        for(column = 0u; column < UI_GLYPH_SIZE; column++)
        {
            if((bits & (uint8_t)(1u << column)) != 0u)
            {
                v5f_display_fill_rect(
                    (uint16_t)(x + (column * scale)),
                    (uint16_t)(y + (row * scale)),
                    scale,
                    scale,
                    color);
            }
        }
    }
}

static void ui_draw_text_n(uint16_t x,
                           uint16_t y,
                           const char *text,
                           uint16_t length,
                           uint16_t scale,
                           uint8_t color)
{
    uint16_t index;

    for(index = 0u; index < length; index++)
    {
        ui_draw_char(x, y, text[index], scale, color);
        x = (uint16_t)(x + (UI_GLYPH_SIZE * scale));
    }
}

static void ui_draw_text(uint16_t x,
                         uint16_t y,
                         const char *text,
                         uint16_t scale,
                         uint8_t color)
{
    ui_draw_text_n(x,
                   y,
                   text,
                   (uint16_t)strlen(text),
                   scale,
                   color);
}

static void ui_draw_border(uint16_t x,
                           uint16_t y,
                           uint16_t width,
                           uint16_t height,
                           uint16_t thickness,
                           uint8_t color)
{
    v5f_display_fill_rect(x, y, width, thickness, color);
    v5f_display_fill_rect(x,
                          (uint16_t)(y + height - thickness),
                          width,
                          thickness,
                          color);
    v5f_display_fill_rect(x, y, thickness, height, color);
    v5f_display_fill_rect((uint16_t)(x + width - thickness),
                          y,
                          thickness,
                          height,
                          color);
}

static void ui_draw_summary(const char *summary, uint8_t summary_len)
{
    uint16_t offset = 0u;
    uint8_t line_index = 0u;

    if(summary_len == 0u)
    {
        ui_draw_text(80u, 198u, "-", 2u, UI_COLOR_WHITE);
        return;
    }

    while((offset < summary_len) && (line_index < UI_SUMMARY_LINES))
    {
        char line[UI_SUMMARY_COLUMNS];
        uint16_t remaining = (uint16_t)(summary_len - offset);
        uint16_t take =
            (remaining > UI_SUMMARY_COLUMNS) ?
                UI_SUMMARY_COLUMNS : remaining;
        uint16_t draw_length = take;
        uint16_t index;

        if(remaining > UI_SUMMARY_COLUMNS)
        {
            for(index = take; index > 0u; index--)
            {
                if(summary[offset + index - 1u] == ' ')
                {
                    take = (uint16_t)(index - 1u);
                    break;
                }
            }
            if(take == 0u)
            {
                take = UI_SUMMARY_COLUMNS;
            }
            draw_length = take;
        }

        for(index = 0u; index < draw_length; index++)
        {
            line[index] = summary[offset + index];
        }
        ui_draw_text_n(80u,
                       (uint16_t)(198u +
                           (line_index * UI_SUMMARY_LINE_PITCH)),
                       line,
                       draw_length,
                       2u,
                       UI_COLOR_WHITE);

        offset = (uint16_t)(offset + take);
        while((offset < summary_len) && (summary[offset] == ' '))
        {
            offset++;
        }
        line_index++;
    }
}

static void ui_draw_option(uint16_t y,
                           const char *label,
                           uint8_t selected)
{
    uint8_t color = (selected != 0u) ? UI_COLOR_BLUE : UI_COLOR_WHITE;

    if(selected != 0u)
    {
        ui_draw_text(88u, y, ">", 3u, color);
    }
    ui_draw_text(136u, y, label, 3u, color);
}

static const char *ui_risk_label(uint8_t risk)
{
    switch(risk)
    {
        case 0u:
            return "LOW";
        case 1u:
            return "MEDIUM";
        case 2u:
            return "HIGH";
        case 3u:
            return "CRITICAL";
        case 4u:
            return "DESTRUCTIVE";
        default:
            return "UNKNOWN";
    }
}

static void ui_draw_approval(const aik_approval_payload_t *payload)
{
    v5f_display_fill(UI_COLOR_BG);
    ui_draw_border(48u, 36u, 704u, 408u, 3u, UI_COLOR_BORDER);

    v5f_display_fill_rect(76u, 68u, 12u, 12u, UI_COLOR_ORANGE);
    ui_draw_text(104u, 60u, "Claude Code approval", 3u, UI_COLOR_WHITE);

    ui_draw_text(80u, 112u, "Tool:", 2u, UI_COLOR_GRAY);
    if(payload->tool_len != 0u)
    {
        ui_draw_text_n(176u,
                       112u,
                       payload->tool,
                       payload->tool_len,
                       2u,
                       UI_COLOR_WHITE);
    }
    else
    {
        ui_draw_text(176u, 112u, "-", 2u, UI_COLOR_WHITE);
    }

    ui_draw_text(80u, 140u, "Risk:", 2u, UI_COLOR_GRAY);
    ui_draw_text(176u,
                 140u,
                 ui_risk_label(payload->risk),
                 2u,
                 UI_COLOR_WHITE);

    ui_draw_text(80u, 174u, "Request:", 2u, UI_COLOR_GRAY);
    ui_draw_summary(payload->summary, payload->summary_len);

    ui_draw_text(80u, 292u, "Do you want to proceed?", 2u, UI_COLOR_WHITE);
    ui_draw_option(326u, "Yes", payload->selected_yes);
    ui_draw_option(366u, "No", (uint8_t)(payload->selected_yes == 0u));

    ui_draw_text(80u,
                 418u,
                 "Fn+stick up/down: select | Fn+knob press: confirm",
                 1u,
                 UI_COLOR_GRAY);
    v5f_display_present();
}

void v5f_approval_ui_init(void)
{
    s_last_sequence = 0u;
}

void v5f_approval_ui_poll(void)
{
    aik_approval_payload_t payload;
    uint32_t published_sequence;
    uint32_t sequence;

    if(v5f_display_is_ready() == 0u)
    {
        return;
    }
    published_sequence = AIK_APPROVAL_MAILBOX->sequence;
    if((published_sequence == 0u) ||
       ((published_sequence & 1u) != 0u) ||
       (published_sequence == s_last_sequence))
    {
        return;
    }
    if(aik_approval_mailbox_read(AIK_APPROVAL_MAILBOX,
                                 &payload,
                                 &sequence) == 0u)
    {
        return;
    }
    if(payload.active != 0u)
    {
        ui_draw_approval(&payload);
    }
    else if((payload.claude_state == AIK_CLAUDE_STATE_RUNNING) ||
            (payload.claude_state == AIK_CLAUDE_STATE_DONE))
    {
        v5f_claude_ui_draw(payload.claude_state);
    }
    else
    {
        v5f_competition_ui_draw();
    }
    s_last_sequence = sequence;
}
